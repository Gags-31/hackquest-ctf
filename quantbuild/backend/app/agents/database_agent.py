"""Database Agent — converts the specification into a database model.

Produces: entity definitions, relationships, an ER diagram (Mermaid), SQL DDL
migration scripts and index/constraint recommendations.
"""
from __future__ import annotations

from typing import Any

from .base import BaseAgent

SQL_TYPES = {
    "str": "VARCHAR(255)",
    "text": "TEXT",
    "int": "INTEGER",
    "float": "FLOAT",
    "bool": "BOOLEAN",
    "datetime": "TIMESTAMP",
    "date": "DATE",
    "fk": "INTEGER",
}


class DatabaseAgent(BaseAgent):
    name = "Database Agent"
    stage = "database_design"

    def run(self) -> dict[str, Any]:
        spec = self.ctx.specification
        self.start("Designing database schema")
        self.rag("database normalization foreign keys indexes constraints", top_k=2)

        entities = spec["entities"]
        relationships = self._relationships(entities)
        ddl = self._ddl(entities)
        er = self._er_diagram(entities, relationships)
        indexes = self._indexes(entities)

        schema = {
            "entities": entities,
            "relationships": relationships,
            "sql": ddl,
            "er_diagram": er,
            "indexes": indexes,
            "migrations": ["migrations/0001_init.sql"],
        }
        self.ctx.database_schema = schema
        self.ctx.save()
        self.done(f"Schema ready: {len(entities)} tables, {len(relationships)} relationships, "
                  f"{len(indexes)} indexes", detail={"tables": [e["table"] for e in entities]})
        return schema

    # ------------------------------------------------------------ derivation
    def _relationships(self, entities: list[dict[str, Any]]) -> list[dict[str, Any]]:
        rels: list[dict[str, Any]] = []
        for ent in entities:
            for field in ent["fields"]:
                if field.get("type") == "fk" and field.get("ref"):
                    rels.append({
                        "from": ent["name"],
                        "to": field["ref"],
                        "type": "one-to-one" if field.get("unique") else "many-to-one",
                        "field": field["name"],
                        "description": f"{ent['name']}.{field['name']} → {field['ref']}.id",
                    })
        return rels

    def _indexes(self, entities: list[dict[str, Any]]) -> list[str]:
        indexes: list[str] = []
        for ent in entities:
            for field in ent["fields"]:
                if field.get("type") == "fk":
                    indexes.append(f"idx_{ent['table']}_{field['name']} on {ent['table']}({field['name']})")
                elif field.get("unique") and not field.get("primary_key"):
                    indexes.append(f"uq_{ent['table']}_{field['name']} UNIQUE on {ent['table']}({field['name']})")
        return indexes

    # ------------------------------------------------------------------- DDL
    def _ddl(self, entities: list[dict[str, Any]]) -> str:
        lines = [
            "-- ============================================================",
            "-- Auto-generated by QuantBuild Database Agent",
            "-- Migration: 0001_init.sql",
            "-- ============================================================",
            "",
        ]
        for ent in entities:
            lines.append(f"CREATE TABLE {ent['table']} (")
            col_lines: list[str] = []
            for field in ent["fields"]:
                col = f"    {field['name']} {SQL_TYPES.get(field['type'], 'VARCHAR(255)')}"
                if field.get("primary_key"):
                    col += " PRIMARY KEY AUTOINCREMENT"
                else:
                    if not field.get("nullable"):
                        col += " NOT NULL"
                    if field.get("unique"):
                        col += " UNIQUE"
                    if "default" in field:
                        default = field["default"]
                        if isinstance(default, bool):
                            default = "1" if default else "0"
                        elif isinstance(default, str):
                            default = f"'{default}'"
                        col += f" DEFAULT {default}"
                if field.get("type") == "fk" and field.get("ref_table"):
                    col += f" REFERENCES {field['ref_table']}(id)"
                if field["name"] == "created_at" and field["type"] == "datetime":
                    col += " DEFAULT CURRENT_TIMESTAMP"
                col_lines.append(col)
            lines.append(",\n".join(col_lines))
            lines.append(");")
            lines.append("")
        for ent in entities:
            for field in ent["fields"]:
                if field.get("type") == "fk":
                    lines.append(f"CREATE INDEX idx_{ent['table']}_{field['name']} "
                                 f"ON {ent['table']}({field['name']});")
        return "\n".join(lines)

    # ------------------------------------------------------------- ER diagram
    def _er_diagram(self, entities: list[dict[str, Any]],
                    relationships: list[dict[str, Any]]) -> str:
        lines = ["erDiagram"]
        for rel in relationships:
            left = "||" if rel["type"] == "one-to-one" else "}|"
            lines.append(f'    {rel["to"].upper()} {left}--o{{ {rel["from"].upper()} : "has"')
        for ent in entities:
            lines.append(f"    {ent['name'].upper()} {{")
            for field in ent["fields"]:
                t = {"str": "string", "text": "string", "int": "int", "float": "float",
                     "bool": "boolean", "datetime": "datetime", "date": "date",
                     "fk": "int"}.get(field["type"], "string")
                key = " PK" if field.get("primary_key") else (" FK" if field["type"] == "fk" else "")
                lines.append(f"        {t} {field['name']}{key}")
            lines.append("    }")
        return "\n".join(lines)
